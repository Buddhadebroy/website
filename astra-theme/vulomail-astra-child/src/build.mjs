#!/usr/bin/env node
/**
 * Builds the theme CSS.
 *
 *   cd src && npm install && npm run build
 *
 * 1. Tailwind 4 (same version as the original site) compiles tw.css → assets/css/vm-tailwind.css.
 *    Cascade layers are removed (Astra's CSS is unlayered and would otherwise always win) and every
 *    utility carries the vm: prefix (tw.css), so no class name clashes with WordPress, Astra or plugins.
 *    Utilities sit under :root to keep the same specificity as before (0,2,0) and beat Astra's element rules,
 *    in the front end and inside the block editor's iframe alike.
 * 2. kadence.src.css (@apply of the original utilities onto the Kadence class names) → assets/css/vm-kadence.css.
 * 3. Every :root variable in the compiled CSS is written to data/root-vars.json, which feeds
 *    Customize → VuloMail → Design tokens.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { transform, Features } from "lightningcss";

const here = path.dirname(fileURLToPath(import.meta.url));
const theme = path.resolve(here, "..");
const cli = path.join(here, "node_modules/@tailwindcss/cli/dist/index.mjs");
const tmp = fs.mkdtempSync(path.join(fs.realpathSync(process.env.TMPDIR || "/tmp"), "vm-build-"));

function tailwind(input, out) {
  execFileSync(process.execPath, [cli, "-i", input, "-o", out], { cwd: here, stdio: ["ignore", "ignore", "inherit"] });
  return fs.readFileSync(out, "utf8");
}

/** Returns [inner, start, end] for the block that opens at index i (pointing at '{'). */
function block(css, i) {
  let depth = 0;
  for (let k = i; k < css.length; k++) {
    if (css[k] === "{") depth++;
    else if (css[k] === "}") {
      depth--;
      if (depth === 0) return [css.slice(i + 1, k), i, k];
    }
  }
  throw new Error("unbalanced css");
}

/** Removes `@layer x;` statements and unwraps `@layer x { … }` blocks. Returns { [layer]: css }. */
function splitLayers(css) {
  css = css.replace(/@layer [\w\s,-]+;/g, "");
  const parts = { none: "" };
  let i = 0;
  while (i < css.length) {
    const at = css.indexOf("@layer", i);
    if (at === -1) {
      parts.none += css.slice(i);
      break;
    }
    parts.none += css.slice(i, at);
    const brace = css.indexOf("{", at);
    const name = css.slice(at + 6, brace).trim();
    const [inner, , end] = block(css, brace);
    parts[name] = (parts[name] || "") + inner;
    i = end + 1;
  }
  return parts;
}

function flatten(css, file) {
  const { code } = transform({
    filename: file,
    code: Buffer.from(css),
    minify: false,
    targets: { chrome: 100 << 16, safari: (15 << 16) | (4 << 8), firefox: 100 << 16 },
    include: Features.Nesting,
  });
  return code.toString();
}

const banner = (what) => `/* VuloMail Astra child: ${what}. Generated by src/build.mjs. Do not edit by hand. */\n`;

// 1. Utilities
const raw = tailwind("tw.css", path.join(tmp, "tw.css"));
const layers = splitLayers(raw);
const props = (raw.match(/@property[^{]+\{[^}]*\}/g) || []).join("\n");
const rootBlocks = [];
let theme_ = (layers.theme || "").replace(/:root,\s*:host\s*\{/, ":root {");
rootBlocks.push(theme_);
let rest = layers.none.replace(/@property[^{]+\{[^}]*\}/g, "");
// keyframes and :root from the unlayered part stay global
// space-y / divide-y use :where(.x > :not(:last-child)) (zero specificity). Inside Astra's .entry-content the
// theme's reset is more specific, so keep the class's own specificity: :where(.x) > :not(:last-child).
const utilitiesRaw = (layers.utilities || "").replace(/:where\((\.[\w\\:.-]*(?:space-[xy]|divide-[xy]?)[\w\\:.-]*) > :not\(:last-child\)\)/g, ":where($1) > :not(:last-child)");
const utilities = `:root {\n${utilitiesRaw}\n}`;
const brand = fs.readFileSync(path.join(here, "brand.css"), "utf8");
let out = banner("Tailwind utilities, vm: prefix") + flatten(`${theme_}\n${rest}\n${utilities}\n${brand}\n${props}`, "vm-tailwind.css");
fs.writeFileSync(path.join(theme, "assets/css/vm-tailwind.css"), out);

// 2. Kadence classes
const kraw = tailwind("kadence.src.css", path.join(tmp, "k.css"));
const klayers = splitLayers(kraw);
const kcss = Object.entries(klayers)
  .filter(([k]) => k !== "theme" && k !== "base" && k !== "properties")
  .map(([, v]) => v)
  .join("\n")
  .replace(/@property[^{]+\{[^}]*\}/g, "");
fs.writeFileSync(path.join(theme, "assets/css/vm-kadence.css"), banner("Kadence block classes (Advanced → Additional CSS class)") + flatten(kcss, "vm-kadence.css"));

// 2b. Block editor variants of the Kadence classes.
// Kadence renders different markup in the editor than on the front end:
//   front:  section.kb-row-layout-wrap.vm-x > .kt-row-column-wrap > .wp-block-kadence-column > .kt-inside-inner-col
//   editor: div.wp-block-kadence-rowlayout.kt-row-column-wrap.vm-x > .innerblocks-wrap > .wp-block-kadence-column > .kadence-inner-column-inner
//   front:  h2.wp-block-kadence-advancedheading.vm-h2
//   editor: div.kb-adv-text.vm-h2 > h2.kadence-advancedheading-text
// Every rule that targets the front-end structure gets an editor copy, scoped to .editor-styles-wrapper.
function splitTop(sel) {
  const parts = [];
  let depth = 0, cur = "";
  for (const ch of sel) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) { parts.push(cur); cur = ""; } else cur += ch;
  }
  parts.push(cur);
  return parts;
}
function editorVariants(css) {
  const out = [];
  function walk(text, wrap) {
    let i = 0;
    while (i < text.length) {
      const open = text.indexOf("{", i);
      if (open === -1) break;
      const prelude = text.slice(i, open).trim();
      const [inner, , end] = block(text, open);
      if (prelude.startsWith("@media") || prelude.startsWith("@supports") || prelude.startsWith("@container")) {
        walk(inner, [...wrap, prelude]);
      } else if (!prelude.startsWith("@") && /kt-row-column-wrap|kt-inside-inner-col|kb-row-layout-wrap/.test(prelude)) {
        const sel = splitTop(prelude)
          .map((x) => x.trim())
          .filter((x) => /kt-row-column-wrap|kt-inside-inner-col|kb-row-layout-wrap/.test(x))
          .map((x) => ".editor-styles-wrapper " + x
            .replace(/\.kb-row-layout-wrap/g, ".wp-block-kadence-rowlayout")
            // In the editor the Row Layout's classes and .kt-row-column-wrap sit on one element, with the columns in
            // its .innerblocks-wrap (kadence-blocks src/blocks/rowlayout/edit.js + row-background.js).
            .replace(/> \.kt-row-column-wrap(?![\w-])/g, "> .innerblocks-wrap")
            .replace(/\.kt-inside-inner-col/g, ".kadence-inner-column-inner"))
          .join(",\n");
        let rule = `${sel} {${inner}}`;
        for (const w of [...wrap].reverse()) rule = `${w} {\n${rule}\n}`;
        out.push(rule);
      }
      i = end + 1;
    }
  }
  walk(css.replace(/\/\*[\s\S]*?\*\//g, ""), []);
  return out.join("\n");
}
const kfinal = fs.readFileSync(path.join(theme, "assets/css/vm-kadence.css"), "utf8");
const editorCss = `${editorVariants(kfinal)}

/* Advanced Text: the class sits on the editor wrapper, the text element inside keeps the editor's own heading
   styles. Let it take the wrapper's typography instead, so headings look like the front end while you type. */
.editor-styles-wrapper .kb-adv-text[class*="vm-"] > .kadence-advancedheading-text {
  margin: 0; font: inherit; color: inherit; letter-spacing: inherit; line-height: inherit;
  text-transform: inherit; text-align: inherit; text-wrap: inherit;
}
.editor-styles-wrapper .kb-adv-text[class*="vm-"] > .kadence-advancedheading-text em { font-style: inherit; }
`;
fs.writeFileSync(path.join(theme, "assets/css/vm-kadence-editor.css"), banner("Kadence classes inside the block editor") + flatten(editorCss, "vm-kadence-editor.css"));

// 3. Design tokens
const vars = {};
for (const css of [out]) {
  for (const m of css.matchAll(/:root\s*\{([^}]*)\}/g)) {
    for (const d of m[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) vars[d[1]] = d[2].trim();
  }
}
const order = (k) => (/^--(paper|surface|ink|line|red|blue|green|amber|code|star|paid)/.test(k) ? 0 : /^--color/.test(k) ? 9 : /^--font/.test(k) ? 1 : /^--(text|leading|tracking|font-weight)/.test(k) ? 2 : /^--(spacing|container|vm-)/.test(k) ? 3 : /^--radius/.test(k) ? 4 : /^--(shadow|blur|ease|default|animate)/.test(k) ? 5 : 6);
const list = Object.keys(vars)
  .filter((k) => !/^--color-/.test(k) && !/^--tw-/.test(k))
  .sort((a, b) => order(a) - order(b))
  .map((k) => ({ name: k, value: vars[k], type: /^#|^rgb|^oklch|^hsl/.test(vars[k]) ? "color" : "text", group: ["Colours", "Fonts", "Type scale", "Spacing & width", "Radii", "Effects & easing", "Other"][order(k)] }));
fs.writeFileSync(path.join(theme, "data/root-vars.json"), JSON.stringify(list, null, 1));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`vm-tailwind.css ${(out.length / 1024).toFixed(1)} KB · vm-kadence.css ok · ${list.length} design tokens`);
