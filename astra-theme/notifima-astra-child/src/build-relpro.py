#!/usr/bin/env python3
"""Pro Release Notes page (Kadence blocks, edited by hand in the editor, not fetched).

Reads src/release-notes-pro.json ([{version, date, items: [[type, text], ...]}, ...], newest first) and writes
data/page-extra/release-notes-pro.php: the hero of the free Release Notes page with Pro text, then one Kadence
Section per version (class "rel") holding
  - Advanced Text  "1.1.7"              (class rel-ver)
  - Advanced Text  "3rd November, 2026" (class rel-date)
  - List           "Added - …" per line (class rel-items)
inc/release-pro.php turns those sections into the same cards, filters and version index as the free page.
Kept outside page-content/ because src/build-kadence.py rebuilds that folder.
"""
import hashlib, html, json, os, re

THEME = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def uid(*parts):
    h = hashlib.md5('|'.join(parts).encode()).hexdigest()
    return 'rp_%s-%s' % (h[:6], h[6:8])


def col(u, cls, inner):
    return ('<!-- wp:kadence/column {"borderWidth":["","","",""],"uniqueID":"%s","direction":["vertical","",""],'
            '"rowGap":[0,"",""],"rowGapVariable":["custom","",""],"kbVersion":2,"className":"%s"} -->\n'
            '<div class="wp-block-kadence-column kadence-column%s kb-section-dir-vertical %s"><div class="kt-inside-inner-col">'
            '%s</div></div>\n<!-- /wp:kadence/column -->' % (u, cls, u, cls, inner))


def text(u, cls, tag, content):
    attrs = '{"uniqueID":"%s"%s,"className":"%s"}' % (u, '' if tag == 'h2' else ',"htmlTag":"%s"' % tag, cls)
    return ('<!-- wp:kadence/advancedheading %s -->\n<%s class="kt-adv-heading%s %s wp-block-kadence-advancedheading" '
            'data-kb-block="kb-adv-heading%s">%s</%s>\n<!-- /wp:kadence/advancedheading -->' % (attrs, tag, u, cls, u, content, tag))


def items(lines):
    li = '\n\n'.join('<!-- wp:list-item -->\n<li>%s - %s</li>\n<!-- /wp:list-item -->' % (html.escape(t), html.escape(x)) for t, x in lines)
    return '<!-- wp:list {"className":"rel-items"} -->\n<ul class="wp-block-list rel-items">%s</ul>\n<!-- /wp:list -->' % li


def version_block(v):
    k = v['version']
    return col(uid('v', k), 'rel', '\n\n'.join([
        text(uid('ver', k), 'rel-ver', 'h2', html.escape(k)),
        text(uid('date', k), 'rel-date', 'div', html.escape(v['date'])),
        items(v['items']),
    ]))


def main():
    vers = json.load(open(os.path.join(THEME, 'src/release-notes-pro.json')))

    # Hero: the free page's hero with new IDs and Pro text.
    free = open(os.path.join(THEME, 'page-content/release-notes.php')).read()
    hero = free[free.index('?>') + 2:].strip()
    # The hero keeps the free page's Kadence IDs, so its per-block CSS (assets/css/nf-blocks.css) applies too.
    hero = hero.replace('<span>Release notes</span>', '<a href="<?php echo esc_url( home_url( \'/release-notes/\' ) ); ?>">Release notes</a>/<span>Notifima Pro</span>')
    hero = hero.replace('>Release <mark class="kt-highlight">notes</mark>', '>Notifima Pro release <mark class="kt-highlight">notes</mark>')
    hero = re.sub(r'>Every update, fix and improvement to Notifima, newest first\.[^<]*<',
                  '>Every update, fix and improvement to Notifima Pro, newest first.<', hero)
    assert 'Notifima Pro release' in hero

    lst = col(uid('list'), 'nf-relpro', '\n\n'.join(version_block(v) for v in vers))
    sec = ('<!-- wp:kadence/rowlayout {"uniqueID":"%s","columns":1,"colLayout":"equal","align":"full","htmlTag":"section",'
           '"padding":[24,28,104,28],"tabletPadding":[24,28,76,28],"mobilePadding":[16,18,76,18],"margin":[0,"",0,""],'
           '"inheritMaxWidth":true,"columnGutter":"none","collapseGutter":"none","kbVersion":2,"className":"nf-k nf-relpro-sec"} -->\n'
           '%s\n<!-- /wp:kadence/rowlayout -->') % (uid('sec'), col(uid('wrap'), 'wrap', lst))

    out = ("<?php\n/**\n * Notifima Pro Release Notes page content: Kadence blocks (generated by src/build-relpro.py from\n"
           " * src/release-notes-pro.json). After the page exists, add new versions in the page editor.\n *\n"
           " * @package Notifima\n */\n\ndefined( 'ABSPATH' ) || exit;\n?>\n%s\n\n%s\n") % (hero, sec)
    os.makedirs(os.path.join(THEME, 'data/page-extra'), exist_ok=True)
    open(os.path.join(THEME, 'data/page-extra/release-notes-pro.php'), 'w').write(out)

    # One empty version, for the "add a version" pattern.
    one = version_block({'version': '1.0.0', 'date': '1st January, 2027', 'items': [
        ['Added', 'Something new.'], ['Fixed', 'Something that was broken.'], ['Update', 'Language file.']]})
    open(os.path.join(THEME, 'data/page-extra/release-pro-version.html'), 'w').write(one + '\n')
    print('versions:', len(vers))


if __name__ == '__main__':
    main()
